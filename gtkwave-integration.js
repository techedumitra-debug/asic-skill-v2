/* ASIC-Skill: GTKWave-compatible VCD and .gtkw export (no external dependencies).
 * Browser waveforms use ASICWaveViewer, not the GTKWave desktop application.
 */
(function(root){
'use strict';
const encoder=new TextEncoder();
function inspect(vcd){
  if(typeof root.ASICParseVCD!=='function')throw new Error('Waveform parser is not available.');
  return root.ASICParseVCD(vcd);
}
function sanitizeSelected(wave,selected){
  const allow=new Set((wave.signals||[]).map(s=>s.name));
  const requested=Array.isArray(selected)?selected.filter(x=>allow.has(x)):[];
  return requested.length?Array.from(new Set(requested)):wave.signals.slice(0,64).map(x=>x.name);
}
function createSavefile(vcd,settings={}){
  const wave=inspect(vcd);
  const names=sanitizeSelected(wave,settings.selected);
  const byName=new Map(wave.signals.map(s=>[s.name,s]));
  const marker=Math.min(wave.end,Math.max(0,Math.floor(Number(settings.marker)||0)));
  const lines=[
    '[*] GTKWave Analyzer save file generated by ASIC-Skill',
    '[dumpfile] wave.vcd',
    '[timestart] 0',
    '[size] 1200 720',
    '[pos] -1 -1',
    '[sst_width] 290',
    '[signals_width] 160',
    '[sst_expanded] 1',
    '[marker] '+marker
  ];
  const scopes=new Set();
  for(const name of names){
    const levels=name.split('.');
    for(let i=1;i<levels.length;i++)scopes.add(levels.slice(0,i).join('.')+'.');
  }
  Array.from(scopes).sort().forEach(s=>lines.push('[treeopen] '+s));
  for(const name of names){
    // GTKWave trace formats: @28 digital / @22 bit vector.
    lines.push(byName.get(name).width>1?'@22':'@28');
    lines.push(name.replace(/[\r\n]/g,''));
  }
  return lines.join('\n')+'\n';
}
const table=(()=>{const arr=new Uint32Array(256);for(let n=0;n<256;n++){let c=n;for(let k=0;k<8;k++)c=(c&1)?0xEDB88320^(c>>>1):c>>>1;arr[n]=c>>>0;}return arr;})();
function crc32(bytes){let crc=0xFFFFFFFF;for(const b of bytes)crc=(crc>>>8)^table[(crc^b)&255];return (crc^0xFFFFFFFF)>>>0;}
function createZip(entries){
  const local=[],central=[];let offset=0;
  for(const {name,text} of entries){
    const n=encoder.encode(name),d=encoder.encode(text),crc=crc32(d);
    if(n.length>65535||d.length>=0xFFFFFFFF)throw Error('Waveform exceeds export limits.');
    const lh=new Uint8Array(30+n.length),lv=new DataView(lh.buffer);
    lv.setUint32(0,0x04034b50,true);lv.setUint16(4,20,true);lv.setUint16(6,0x800,true); // UTF-8
    lv.setUint32(14,crc,true);lv.setUint32(18,d.length,true);lv.setUint32(22,d.length,true);
    lv.setUint16(26,n.length,true);lh.set(n,30);local.push(lh,d);
    const ch=new Uint8Array(46+n.length),cv=new DataView(ch.buffer);
    cv.setUint32(0,0x02014b50,true);cv.setUint16(4,20,true);cv.setUint16(6,20,true);
    cv.setUint16(8,0x800,true);cv.setUint32(16,crc,true);cv.setUint32(20,d.length,true);
    cv.setUint32(24,d.length,true);cv.setUint16(28,n.length,true);cv.setUint32(42,offset,true);
    ch.set(n,46);central.push(ch);offset+=lh.length+d.length;
  }
  const length=central.reduce((sum,b)=>sum+b.length,0),end=new Uint8Array(22),dv=new DataView(end.buffer);
  dv.setUint32(0,0x06054b50,true);dv.setUint16(8,entries.length,true);dv.setUint16(10,entries.length,true);
  dv.setUint32(12,length,true);dv.setUint32(16,offset,true);
  return new Blob([...local,...central,end],{type:'application/zip'});
}
function download(blob,name){
  const href=URL.createObjectURL(blob),a=document.createElement('a');a.href=href;a.download=name;
  document.body.append(a);a.click();a.remove();setTimeout(()=>URL.revokeObjectURL(href),2000);
}
function exportBundle(vcd,settings={}){
  const savefile=createSavefile(vcd,settings);
  const readme='ASIC-Skill GTKWave session\n\n1. Extract this ZIP into one folder.\n2. Install GTKWave on your own computer (native desktop application).\n3. Run: gtkwave wave.vcd wave.gtkw\n\nBrowser waveform viewing is available separately in ASIC-Skill.\n';
  const zip=createZip([{name:'wave.vcd',text:vcd},{name:'wave.gtkw',text:savefile},{name:'README.txt',text:readme}]);
  if(settings.download!==false)download(zip,'asic-skill-gtkwave-session.zip');
  return zip;
}
function openWorkspace(source){
  const popup=root.open('gtkwave-workspace.html?source='+encodeURIComponent(source),'_blank');
  if(!popup)throw new Error('Allow pop-up windows for this site to open the waveform workspace.');
  return popup;
}
root.ASICGTKWave={createSavefile,createZip,exportBundle,openWorkspace,inspect};
})(window);
